//! Splits an assembly DXF (every part of the product in its own block) into one-part-per-file DXFs.

use anyhow::{bail, Context, Result};
use dxf::entities::EntityType;
use dxf::tables::Layer;
use dxf::{Block, Drawing};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

/// Case-insensitive glob match: `*` is any string, `?` is one character.
pub fn glob_match(pattern: &str, name: &str) -> bool {
    fn rec(p: &[char], n: &[char]) -> bool {
        match (p.first(), n.first()) {
            (None, None) => true,
            (Some('*'), _) => rec(&p[1..], n) || (!n.is_empty() && rec(p, &n[1..])),
            (Some('?'), Some(_)) => rec(&p[1..], &n[1..]),
            (Some(a), Some(b)) if a.eq_ignore_ascii_case(b) => rec(&p[1..], &n[1..]),
            _ => false,
        }
    }
    let p: Vec<char> = pattern.chars().collect();
    let n: Vec<char> = name.chars().collect();
    rec(&p, &n)
}

#[derive(Debug, Clone)]
pub struct ExtractedBlock {
    pub name: String,
    pub path: PathBuf,
    /// How many times the block is inserted in the source model space.
    pub inserts: usize,
}

/// Saves every block whose name matches one of the patterns to `out_dir/<name>.dxf`
/// and writes `parts.toml` with quantity 1 (the insert count goes into a comment).
pub fn extract_blocks(src: &Path, patterns: &[String], out_dir: &Path) -> Result<Vec<ExtractedBlock>> {
    let d = Drawing::load_file(src).with_context(|| format!("{}: cannot read DXF", src.display()))?;
    let mut inserts: BTreeMap<String, usize> = BTreeMap::new();
    for e in d.entities() {
        if let EntityType::Insert(i) = &e.specific {
            *inserts.entry(i.name.clone()).or_default() += 1;
        }
    }
    let blocks: BTreeMap<&str, &Block> = d.blocks().map(|b| (b.name.as_str(), b)).collect();
    let selected: Vec<&Block> = blocks
        .values()
        .copied()
        // `*Model_Space` and friends are layout blocks; names with `$` are anonymous CAD-generated blocks.
        .filter(|b| !b.name.starts_with('*') && !b.name.contains('$') && patterns.iter().any(|p| glob_match(p, &b.name)))
        .collect();
    // Block definitions never inserted in model space are leftovers in the drawing, not parts.
    let (selected, unused): (Vec<&Block>, Vec<&Block>) = selected.into_iter().partition(|b| inserts.contains_key(&b.name));
    if !unused.is_empty() {
        log::warn!(
            "skipped blocks not inserted in the drawing: {}",
            unused.iter().map(|b| b.name.as_str()).collect::<Vec<_>>().join(", ")
        );
    }
    if selected.is_empty() {
        bail!("{}: no blocks match {:?}", src.display(), patterns);
    }
    fs::create_dir_all(out_dir).with_context(|| format!("{}: cannot create directory", out_dir.display()))?;

    let mut out = Vec::new();
    for b in selected {
        let mut nd = Drawing::new();
        nd.header.version = d.header.version;
        nd.header.default_drawing_units = d.header.default_drawing_units;

        // Nested blocks are copied along with the part.
        let mut needed = BTreeSet::new();
        collect_nested(b, &blocks, &mut needed);
        for name in &needed {
            let mut nb = (*blocks[name.as_str()]).clone();
            for e in &mut nb.entities {
                e.common.handle = dxf::Handle::empty();
            }
            nd.add_block(nb);
        }

        // Layers go in before the entities: adding an entity creates a missing layer with default
        // settings, which would shadow the source layer's colour.
        let layers: BTreeSet<String> = b.entities.iter().map(|e| e.common.layer.clone()).collect();
        for l in layers.iter().filter(|l| l.as_str() != "0") {
            let src = d.layers().filter(|x| &x.name == l).last();
            let color = src.map(|x| x.color.clone()).unwrap_or_default();
            let line_type_name = src.map(|x| x.line_type_name.clone()).unwrap_or_else(|| "CONTINUOUS".into());
            nd.add_layer(Layer { name: l.clone(), color, line_type_name, ..Default::default() });
        }
        for e in &b.entities {
            nd.add_entity(e.clone());
        }

        let path = out_dir.join(format!("{}.dxf", sanitize(&b.name)));
        nd.save_file(&path).with_context(|| format!("{}: cannot write", path.display()))?;
        out.push(ExtractedBlock { name: b.name.clone(), path, inserts: inserts.get(&b.name).copied().unwrap_or(0) });
    }

    let mut manifest = String::from("# Quantity of each part. Generated by `nest extract`; check and edit.\n[parts]\n");
    for x in &out {
        let stem = x.path.file_stem().unwrap().to_string_lossy();
        let _ = writeln!(manifest, "\"{stem}\" = 1  # inserts in the drawing: {}", x.inserts);
    }
    let mpath = out_dir.join("parts.toml");
    if mpath.exists() {
        log::warn!("{} already exists, not overwriting", mpath.display());
    } else {
        fs::write(&mpath, manifest).with_context(|| format!("{}: cannot write", mpath.display()))?;
    }
    Ok(out)
}

fn collect_nested(b: &Block, blocks: &BTreeMap<&str, &Block>, needed: &mut BTreeSet<String>) {
    for e in &b.entities {
        if let EntityType::Insert(i) = &e.specific
            && let Some(nb) = blocks.get(i.name.as_str())
            && needed.insert(i.name.clone())
        {
            collect_nested(nb, blocks, needed);
        }
    }
}

/// Block name -> file name.
fn sanitize(name: &str) -> String {
    name.chars().map(|c| if c.is_alphanumeric() || "-_. ".contains(c) { c } else { '_' }).collect()
}

